package com.elishaazaria.sayboard.desktop

import java.util.Locale

enum class Lang(val code: String, val label: String) {
    EN("en", "English"),
    FA("fa", "فارسی");

    companion object {
        fun fromCode(code: String?): Lang? = values().firstOrNull { it.code == code }

        /** Picks Persian for Persian speaking systems, English otherwise. */
        fun detect(): Lang {
            val locale = Locale.getDefault()
            return if (locale.language == "fa" || locale.language == "ar" || locale.language == "ps") {
                FA
            } else {
                EN
            }
        }
    }
}

/**
 * Every text of the window, in English and Persian. Missing keys fall back to
 * English, and a unit test makes sure both tables always have the same keys.
 */
class Strings(val lang: Lang) {
    private val table: Map<String, String> =
        if (lang == Lang.FA) PersianTexts.table else EnglishTexts.table

    operator fun get(key: String): String = table[key] ?: EnglishTexts.table[key] ?: key

    fun f(key: String, vararg args: Any?): String = String.format(get(key), *args)

    val isRtl: Boolean
        get() = lang == Lang.FA

    companion object {
        val english = Strings(Lang.EN)
        val persian = Strings(Lang.FA)
        fun of(lang: Lang): Strings = if (lang == Lang.FA) persian else english
        fun keys(): Set<String> = EnglishTexts.table.keys
    }
}

